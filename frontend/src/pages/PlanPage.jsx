import { useEffect, useState } from "react";
import { api, errMsg } from "../lib/api.js";
import { useSearchParams, Link } from "react-router-dom";
import { GOALS, DIETS, ACTIVITY } from "../lib/constants.js";
import { Hero } from "../components/ui.jsx";
import { useAuth } from "../lib/AuthContext.jsx";

const EXP = [["beginner", "Beginner - under 1 year"], ["intermediate", "Intermediate - 1-3 years"], ["advanced", "Advanced - 3+ years"]];
const Pick = ({ items, value, onChange }) => (
  <div className="grid gap-2 sm:grid-cols-2">{items.map(([k, t, d]) => (
    <button type="button" key={k} onClick={() => onChange(k)} aria-pressed={value === k} className={`rounded-xl border px-3.5 py-3 text-left transition ${value === k ? "border-emerald/70 bg-emerald/10" : "border-line bg-tile hover:border-mute/50"}`}>
      <div className="text-sm font-medium">{t}</div>{d && <div className="text-xs text-mute">{d}</div>}</button>))}</div>
);

export function PlanView({ plan }) {
  const [day, setDay] = useState("Day 1"), t = plan.targets;
  return (
    <div className="space-y-8">
      <section className="grid gap-4 sm:grid-cols-5">
        {[["Calories", t.kcal, "kcal"], ["Protein", t.protein, "g"], ["Carbs", t.carbs, "g"], ["Fat", t.fat, "g"], ["Fibre", t.fibre, "g"]].map(([l, v, u]) => (
          <div key={l} className="card py-4 px-5"><div className="mono-label">{l}</div><div className="mt-1 text-3xl font-extrabold">{v}<span className="ml-1 text-sm font-normal text-mute">{u}</span></div></div>))}
      </section>
      <p className="text-sm text-mute">BMR {plan.bmr} kcal · maintenance (TDEE) {plan.tdee} kcal · generated by {plan.generator === "template+llm" ? "template engine with AI personalisation" : "the template engine"}.</p>
      {plan.coachNote && <p className="card p-5 text-sm">{plan.coachNote}</p>}

      <section>
        <div className="mb-3 flex flex-wrap items-center gap-2"><h2 className="text-xl font-extrabold">Meals</h2>
          {Object.keys(plan.weeklyMeals || {}).map(d => <button key={d} onClick={() => setDay(d)} className={`chip ${day === d ? "chip-on" : ""}`}>{d}</button>)}</div>
        <div className="rule">{(plan.weeklyMeals?.[day] || plan.meals).map(m => (
          <div key={m.meal} className="flex items-baseline justify-between gap-4 border-b border-line py-3"><div><span className="mr-3 text-sm text-mute">{m.meal}</span>{m.food}</div><span className="text-sm text-mute">{m.kcal} kcal</span></div>))}</div>
      </section>

      <section>
        <h2 className="mb-3 text-xl font-extrabold">Micronutrient focus</h2>
        <div className="grid gap-3 md:grid-cols-2">{plan.micronutrients.map(m => (
          <div key={m.name} className="card p-5"><div className="flex justify-between"><b>{m.name}</b><span className="text-sm text-mint">{m.target}</span></div><div className="mt-1 text-xs text-mute">{m.sources.join(" · ")}</div><p className="mt-2 text-xs">{m.note}</p></div>))}</div>
      </section>

      <section>
        <h2 className="mb-3 text-xl font-extrabold">Weekly training</h2>
        <div className="grid gap-4 md:grid-cols-2">{plan.workouts.map(w => (
          <div key={w.day} className="card p-5"><div className="mb-2 flex justify-between"><b>{w.focus}</b><span className="text-sm text-mute">{w.day}</span></div>
            {w.exercises.map(e => <div key={e.name} className="flex justify-between border-t border-line py-1.5 text-sm"><span>{e.name}</span><span className="text-mute">{e.sets} × {e.reps}{e.rest !== "-" && ` · rest ${e.rest}`}</span></div>)}</div>))}</div>
      </section>
    </div>
  );
}

export default function PlanPage() {
  const { user, refresh } = useAuth(), p = user?.profile || {}, [qs] = useSearchParams();
  const [plan, setPlan] = useState(null), [edit, setEdit] = useState(false), [step, setStep] = useState(0), [busy, setBusy] = useState(false), [err, setErr] = useState("");
  const [f, setF] = useState({ age: p.age || "", gender: p.gender || "male", height: p.height || "", weight: p.weight || "", fitnessGoal: p.fitnessGoal || "hypertrophy", experience: p.experience || "beginner", activityLevel: p.activityLevel || "moderate", dietType: p.dietType || "veg", notes: "" });
  const set = k => v => setF(x => ({ ...x, [k]: v })), inp = k => e => set(k)(e.target.value);

  useEffect(() => { api.get("/plans/current").then(r => { setPlan(r.data.plan); setEdit(!r.data.plan || qs.get("edit") === "1"); }).catch(() => setEdit(true)); }, []);
  const generate = async () => {
    setBusy(true); setErr("");
    try { const { data } = await api.post("/plans", f); setPlan(data.plan); setEdit(false); setStep(0); refresh(); } catch (e) { setErr(errMsg(e)); } finally { setBusy(false); }
  };
  const bodyOk = f.age >= 10 && f.height >= 100 && f.weight >= 25;
  const steps = [
    <div key="0" className="grid gap-4 sm:grid-cols-2">
      <div><label className="label" htmlFor="a">Age</label><input id="a" type="number" className="field" value={f.age} onChange={inp("age")} /></div>
      <div><label className="label" htmlFor="g">Sex (for the BMR equation)</label><select id="g" className="field" value={f.gender} onChange={inp("gender")}><option value="male">Male</option><option value="female">Female</option></select></div>
      <div><label className="label" htmlFor="h">Height (cm)</label><input id="h" type="number" className="field" value={f.height} onChange={inp("height")} /></div>
      <div><label className="label" htmlFor="w">Weight (kg)</label><input id="w" type="number" className="field" value={f.weight} onChange={inp("weight")} /></div></div>,
    <div key="1" className="space-y-5"><div><div className="label">Main goal</div><Pick items={GOALS} value={f.fitnessGoal} onChange={set("fitnessGoal")} /></div><div><div className="label">Training experience</div><Pick items={EXP} value={f.experience} onChange={set("experience")} /></div></div>,
    <div key="2" className="space-y-5"><div><div className="label">Daily activity</div><Pick items={ACTIVITY} value={f.activityLevel} onChange={set("activityLevel")} /></div><div><div className="label">Diet</div><Pick items={DIETS} value={f.dietType} onChange={set("dietType")} /></div>
      <div><label className="label" htmlFor="nt">Anything else? (allergies, foods you dislike) - used if AI personalisation is enabled</label><input id="nt" className="field" value={f.notes} onChange={inp("notes")} /></div></div>,
  ];
  const titles = ["Your body", "Goal and experience", "Lifestyle and diet"];

  if (!edit && plan) return (
    <div><div className="mb-6 flex items-center justify-between"><div><span className="pill">Active Diet &amp; Training Plan</span><h1 className="mt-3 text-3xl font-extrabold">Your Plan</h1></div><button className="btn-dark" onClick={() => setEdit(true)}>Regenerate</button></div><PlanView plan={plan} /></div>);
  return (
    <div className="mx-auto max-w-2xl">
      <h1 className="text-3xl font-extrabold">Plan wizard</h1><p className="mt-1 text-sm text-mute">Step {step + 1} of 3 · {titles[step]}</p>
      <div className="mt-6 card p-6">{steps[step]}
        {err && <p role="alert" className="mt-4 text-sm text-rose">{err}</p>}
        <div className="mt-6 flex justify-between"><button className="btn-dark" disabled={step === 0} onClick={() => setStep(step - 1)}>Back</button>
          {step < 2 ? <button className="btn-mint" disabled={step === 0 && !bodyOk} onClick={() => setStep(step + 1)}>Next</button> : <button className="btn-mint" disabled={busy || !bodyOk} onClick={generate}>{busy ? "Generating…" : "Generate my plan"}</button>}</div></div>
      {plan && <button className="mt-4 text-sm text-mute hover:text-paper" onClick={() => setEdit(false)}>Keep my current plan</button>}
    </div>
  );
}
